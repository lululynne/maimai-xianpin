import assert from 'node:assert/strict';
import { pickHostDefault } from '../src/domain/groups.js';
import { readFile } from 'node:fs/promises';
import { test } from 'node:test';
import { createApp } from '../src/app.js';
import { Catalog } from '../src/catalog.js';
import { Repository } from '../src/db.js';
import { Groups } from '../src/domain/groups.js';
import { DemoMcpClient } from '../src/mcp/demo.js';

test('two browser cookies share SQLite state while ownership and account tools stay isolated', async () => {
  const snapshot = JSON.parse(await readFile('fixtures/mcp-calls.json', 'utf8'));
  const repo = new Repository(':memory:', 'demo');
  try {
    const menuTime = () => Date.parse('2026-10-18T00:30:00Z');
    const catalog = new Catalog(new DemoMcpClient(snapshot, menuTime), Date.now, 3000, undefined, menuTime);
    const app = createApp({ catalog, groups: new Groups(repo), mode: 'demo', now: Date.now, speed: 1, capturedAt: snapshot.calls[0].capturedAt });
    const first = await app.request('/api/config'); const setCookie = first.headers.get('set-cookie')!;
    assert.match(setCookie, /HttpOnly/); assert.match(setCookie, /SameSite=Strict/i);
    const host = setCookie.split(';')[0]!;
    const visitor = (await app.request('/api/config')).headers.get('set-cookie')!.split(';')[0]!;
    const json = (cookie: string, body: unknown) => ({ method: 'POST', headers: { Cookie: cookie, 'Content-Type': 'application/json' }, body: JSON.stringify(body) });
    assert.equal((await app.request('/api/config', { headers: { Origin: 'https://elsewhere.example' } })).status, 403);
    assert.equal((await app.request('/api/tools/call', json(visitor, { name: 'create-order' }))).status, 404);
    assert.equal((await app.request('/api/groups', { method: 'POST', body: '{}' })).status, 415);
    const meal = await catalog.meal('1420082', '9900016136');
    const created = await app.request('/api/groups', json(host, { storeCode: '1420082', mealCode: meal.code, nickname: '发起人', tail4: '1234', minutes: 30, people: 2, partIds: pickHostDefault(meal), confirmedSimilar: true }));
    assert.equal(created.status, 201);
    const { group } = await created.json();
    const board = await (await app.request('/api/groups?store=1420082', { headers: { Cookie: visitor } })).json();
    assert.ok(board.groups.some((g: any) => g.id === group.id));
    assert.equal(board.groups.find((g: any) => g.id === group.id).members[0].tail4, undefined);
    const response = await app.request(`/api/groups/${group.id}/join`, json(visitor, { nickname: '来拼的', tail4: '5678', partIds: meal.parts.map(p => p.id).filter(id => !pickHostDefault(meal).includes(id)) }));
    assert.equal(response.status, 200);
    assert.equal((await response.json()).group.state, 'full');
    assert.equal((await app.request(`/api/groups/${group.id}/confirm`, json(visitor, {}))).status, 200);
    assert.equal((await app.request(`/api/groups/${group.id}/ordered`, json(visitor, {}))).status, 403);
    assert.equal((await app.request(`/api/groups/${group.id}/ordered`, json(host, {}))).status, 200);
    assert.equal((await app.request(`/api/groups/${group.id}/picked-up`, json(host, {}))).status, 200);
    const mine = await (await app.request('/api/mine', { headers: { Cookie: visitor } })).json();
    const completed = mine.groups.find((g: any) => g.id === group.id);
    assert.equal(completed.state, 'picked-up');
    assert.equal(completed.viewerId, completed.members[1].id);
    assert.ok(!JSON.stringify(mine).includes('device'));
    const draft = await (await app.request('/api/groups', json(host, { storeCode: '1420082', mealCode: meal.code, nickname: '演示发起人', tail4: '2468', partIds: pickHostDefault(meal), people: 3, confirmedSimilar: true }))).json();
    assert.equal((await app.request(`/api/demo/groups/${draft.group.id}/fill`, json(visitor, {}))).status, 403);
    const simulated = await app.request(`/api/demo/groups/${draft.group.id}/fill`, json(host, {}));
    assert.equal(simulated.status, 200);
    const full = (await simulated.json()).group;
    assert.equal(full.state, 'full');
    assert.ok(full.members.every((m: any) => m.confirmed));
    const liveApp = createApp({ catalog, groups: new Groups(repo), mode: 'live', now: Date.now, speed: 1, capturedAt: '' });
    assert.equal((await liveApp.request(`/api/demo/groups/${draft.group.id}/fill`, json(host, {}))).status, 404);
  } finally { repo.close(); }
});
